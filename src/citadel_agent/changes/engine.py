"""Prepare and execute change sets.

``prepare`` is non-mutating for Azure: it authorizes, checks caps and compatibility, renders the
intents into the agent's working clone, compiles them and previews them with what-if, then stores
an immutable change set. ``execute`` requires the approved content hash, re-verifies that nothing
drifted since preparation and then either deploys directly (and records the result in the
canonical repository) or opens a pull request, depending on the admin policy.
"""

