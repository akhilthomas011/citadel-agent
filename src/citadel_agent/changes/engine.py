MAX_WHAT_IF_CHANGES = 50
RAWXML_POLICY_NOISE = "apim-rawxml-policy"
EXTRA_FILE_PREFIXES = (".citadel/rotations/",)
# States after which a change set never runs again (recorded by ``_record_change``, or abandoned).
EXECUTED_STATES = frozenset(
    {"recorded", "awaiting-merge", "branch-pushed", "committed-locally", "record-failed", "abandoned"}
)


class ChangeError(RuntimeError):
    """Raised when a change cannot be prepared or executed. Nothing is deployed when this is raised."""


class DeploymentRunnerLike(Protocol):
    def what_if(self, target: DeploymentTarget, name: str, compiled: CompiledDeployment) -> WhatIfReport: ...

    def deploy(
        self, target: DeploymentTarget, name: str, compiled: CompiledDeployment
    ) -> DeploymentRecord: ...


@dataclass(frozen=True)
class IntentChange:
    """One intent to create or update, as a deploy step of the change set."""

    step_id: str
    intent: ContractIntent
    operation: Operation
    depends_on: tuple[str, ...] = ()


@dataclass(frozen=True)
class PrerequisiteStep:
    """An action outside Citadel's contracts (for example an RBAC assignment) done by an authorized person."""

    step_id: str
    description: str
    commands: tuple[str, ...]
    verification: str
    depends_on: tuple[str, ...] = ()


@dataclass(frozen=True)
class ChangeRequest:
    summary: str
    environment: str
    changes: tuple[IntentChange, ...]
    prerequisites: tuple[PrerequisiteStep, ...] = ()
    # Agent-owned state files committed with the change (path, content), e.g. rotation state.
    extra_files: tuple[tuple[str, str], ...] = ()


@dataclass(frozen=True)
class PreparedChange:
    change: ChangeSet
    content_hash: str

    def summary(self) -> str:
        """Human-readable summary shown before approval."""
        lines = [
            f"Change set {self.change.id} ({self.change.mode.upper()} mode, environment "
            f"{self.change.environment}/{self.change.environment_class})",
            f"Summary: {clean_text(self.change.summary)}",
        ]
        for step in self.change.ordered_steps():
            if step.kind is StepKind.PREREQUISITE:
                lines.append(f"- [{step.id}] prerequisite (manual): {step.description}")
                continue
            lines.append(f"- [{step.id}] deploy {step.template} as {step.deployment_name}")
            if step.what_if_deferred:
                lines.append("    what-if: deferred until its dependencies are deployed")
            elif step.what_if is not None:
                counts = (
                    ", ".join(f"{k}: {v}" for k, v in sorted(step.what_if.counts.items())) or "no changes"
                )
                lines.append(f"    what-if: {counts}")
                lines.extend(f"      {line}" for line in step.what_if.changes[:20])
                lines.extend(f"      expected: {line}" for line in step.what_if.expected_noise)
                lines.extend(f"      note: {line}" for line in step.what_if.diagnostics[:10])
                if step.what_if.error:
                    lines.append(f"    what-if error: {step.what_if.error}")
        lines.extend(f"Warning: {w}" for w in self.change.warnings)
        lines.append(f"Approval hash: {self.content_hash}")
        return "\n".join(lines)


@dataclass
class EngineServices:
    """Collaborators of the change engine (injected for testing)."""

    workspace: CanonicalWorkspace
    store: ChangeStore
    authorizer: Authorizer
    agent_lock: UpstreamLock
    agent_version: str
    runner_factory: Callable[[str], DeploymentRunnerLike]
    live_release: Callable[[EnvironmentPolicy], dict[str, str] | None]
    can_deploy: Callable[[EnvironmentPolicy], bool]
    audit: AuditLog
    git_provider: GitProvider | None = None
    compile: Callable[[Path], CompiledDeployment] = compile_deployment
    reload_policy: Callable[[], LoadedPolicy] | None = None
    clock: Callable[[], datetime] = field(default=lambda: datetime.now(UTC))


def _sha256(text: str) -> str:
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


def _summarize_what_if(report: WhatIfReport, *, policy_changed: bool = False) -> WhatIfSummary:
    """Summarize a what-if; ``policy_changed`` means the rendered policy XML really changed."""
    redactor = default_redactor()
    catalogs = load_catalogs()
    created = [c.resource_id for c in report.changes if c.change_type == "Create" and not c.potential]
    changes: list[str] = []
    noise: dict[str, str] = {}
    for change in report.changes:
        if change.change_type in NO_CHANGE_TYPES:
            continue
        line = f"{change.label}: {change.resource_id}"
        if change.property_changes:
            line += f" ({'; '.join(change.property_changes[:5])})"
        known = catalogs.classify_noise(
            change.resource_id, change.change_type, change.property_changes, created=created
        )
        if known is not None and known.id == RAWXML_POLICY_NOISE and policy_changed:
            known = None  # the policy really changes in this step
        if known is not None:
            line += f" [expected: {known.id}]"
            noise[known.id] = f"{known.id}: {known.explanation}"
        changes.append(line)
    return WhatIfSummary(
        status=report.status,
        counts=report.counts(),
        fingerprint=report.fingerprint(),
        changes=changes[:MAX_WHAT_IF_CHANGES],
        expected_noise=sorted(noise.values()),
        diagnostics=[redactor.redact(d)[:500] for d in report.diagnostics[:MAX_WHAT_IF_CHANGES]],
        error=report.error,
    )


def _safe_outputs(record: DeploymentRecord) -> dict[str, Any]:
    """Deployment outputs without secrets (direct-output credentials are dropped entirely)."""
    safe: dict[str, Any] = {}
    for name, entry in record.outputs.items():
        if name == "endpoints" or is_sensitive_key(name):
            continue
        value = entry.get("value") if isinstance(entry, dict) else entry
        safe[name] = default_redactor().redact_obj(value)
    return safe


class ChangeEngine:
    def __init__(self, services: EngineServices) -> None:
        self.s = services

    # ------------------------------------------------------------------ prepare
    def _environment(self, name: str) -> EnvironmentPolicy:
        policy = self.s.authorizer.policy
        if policy is None:
            raise ChangeError(self.s.authorizer.loaded.error or "No admin policy is loaded")
        return policy.environment(name)

    def _authorize(self, request: ChangeRequest) -> None:
        auth = self.s.authorizer
        repo = self.s.workspace.repository
        for change in request.changes:
            auth.require(change.operation)
            if change.intent.environment != request.environment:
                raise ChangeError(
                    f"Step {change.step_id} targets {change.intent.environment}, not {request.environment}"
                )
            existing = repo.find(intent_directory(change.intent)) if (repo.root / ".git").exists() else None
            auth.require_owner(existing or change.intent)
            problems = auth.check_caps(change.intent)
            if problems:
                raise ChangeError("Admin policy caps violated: " + "; ".join(problems))
            if isinstance(change.intent, AccessContractIntent):
                rotation = read_rotation_state(repo.root, str(intent_directory(change.intent)))
                if (
                    rotation is not None
                    and rotation.locked
                    and change.operation is not Operation.ROTATION_WRITE
                ):
                    raise ChangeError(
                        f"A key rotation is in progress for this contract (step {rotation.phase}); "
                        "finish it or roll it back before other changes"
                    )
                clashes = self._secret_collisions(change.intent)
                if clashes:
                    raise ChangeError(
                        "Another contract already writes these Key Vault secrets: "
                        + ", ".join(clashes)
                        + "; deploying would overwrite its key"
                    )

    def _secret_collisions(self, intent: AccessContractIntent) -> list[str]:
        vault = self._environment(intent.environment).key_vault
        repo = self.s.workspace.repository
        if vault is None or not (repo.root / ".git").exists():
            return []
        mine = intent.key_vault_secret_names()
        directory = str(intent_directory(intent))
        clashes: set[str] = set()
        for record in repo.intents("access-contract"):
            other = record.intent
            if (
                str(intent_directory(other)) == directory
                or other.environment not in self.s.authorizer.policy.environments
            ):
                continue
            other_vault = self._environment(other.environment).key_vault
            if other_vault is not None and other_vault.name.lower() == vault.name.lower():
                clashes |= mine & other.key_vault_secret_names()
        return sorted(clashes)

    def _compat(
        self, request: ChangeRequest, env: EnvironmentPolicy
    ) -> tuple[dict[str, str] | None, list[str]]:
        tested = self.s.agent_lock.upstream.release
        live = self.s.live_release(env)
        warnings: list[str] = []
        report = assess_release(live, tested)
        repo_release = read_release(self.s.workspace.repository.upstream_root)
        repo_report = assess_release(repo_release, tested)
        for change in request.changes:
            capability = OPERATION_CAPABILITY[change.operation]
            for label, rep in (("live gateway", report), ("contracts repository upstream", repo_report)):
                if not rep.writes_allowed(capability):
                    reasons = "; ".join(f"{a.track}: {a.reason}" for a in rep.problems())
                    raise ChangeError(
                        f"The {label} is not compatible with this agent build for {capability}: {reasons}"
                    )
        warnings.extend(f"live {a.track}: {a.reason}" for a in report.problems())
        warnings.extend(f"repository upstream {a.track}: {a.reason}" for a in repo_report.problems())
        return live, warnings

    def _stale_generated_files(self, directory: str, rendered: set[str]) -> list[str]:
        folder = self.s.workspace.path / Path(*directory.split("/"))
        stale = []
        if folder.is_dir():
            for path in folder.iterdir():
                relative = f"{directory}/{path.name}"
                if (
                    path.is_file()
                    and relative not in rendered
                    and GENERATED_MARKER in path.read_text(encoding="utf-8")
                ):
                    stale.append(relative)
        return stale

    def _refuse_pending_changes(self, request: ChangeRequest, warnings: list[str]) -> None:
        """Refuse to stack a change on a contract that already has an open agent pull request.

        The base branch does not contain pending changes yet, so preparing another change from it
        would silently revert them (including changes already deployed directly).
        """
        provider = self.s.git_provider
        policy = self.s.authorizer.policy
        if provider is None or policy is None or self.s.workspace.remote_is_local():
            return
        directories = {str(intent_directory(c.intent)) for c in request.changes}
        if not directories:
            return
        try:
            pending = provider.open_pull_requests(labels=list(policy.gitops.labels))
        except GitProviderError as exc:
            warnings.append(f"Could not check for pending pull requests: {exc}")
            return
        for pr in pending:
            overlap = sorted(d for d in directories if any(f.startswith(f"{d}/") for f in pr.files))
            if overlap:
                raise ChangeError(
                    f"{', '.join(overlap)} already has a pending change in pull request #{pr.number} "
                    f"({pr.url}). Merge or close it before preparing another change."
                )

    def prepare(self, request: ChangeRequest) -> PreparedChange:
        """Validate, render, compile and preview a change. Never modifies Azure resources."""
        if not request.changes and not request.prerequisites:
            raise ChangeError("Nothing to change")
        env = self._environment(request.environment)
        base_commit = self.s.workspace.sync_base()
        self._authorize(request)
        live, warnings = self._compat(request, env)
        self._refuse_pending_changes(request, warnings)

        mode = env.mode.value
        if env.mode is ChangeMode.DIRECT and not self.s.can_deploy(env):
            if not env.fallback_to_pr:
                raise ChangeError(
                    "You cannot deploy to this environment directly and fallbackToPr is disabled"
                )
            mode = ChangeMode.PR.value
            warnings.append(
                "You lack direct deployment rights here, so this change will be proposed as a pull request."
            )

        now = self.s.clock()
        change_id = new_change_id(now)
        repo = self.s.workspace.repository
        repo_upstream = repo.upstream_commit()
        kinds = sorted({c.intent.kind.replace("-contract", "") for c in request.changes}) or ["prerequisites"]
        branch = f"citadel-agent/{'-'.join(kinds)}/{request.environment}-{change_id}"
        self.s.workspace.begin_branch(branch)

        target = env.to_target(request.environment)
        files: dict[str, str] = {}
        steps: list[ChangeStep] = []
        template_hashes: dict[str, str] = {}
        stamp = now.strftime("%y%m%d%H%M%S")
        deploy_ids = {c.step_id for c in request.changes}
        for change in request.changes:
            rendered = render_intent(
                change.intent,
                RenderContext(
                    repo_root=self.s.workspace.path,
                    upstream_root=repo.upstream_root,
                    target=target,
                    upstream_commit=repo_upstream,
                ),
            )
            step_files = {str(path): content for path, content in rendered.files.items()}
            for stale in self._stale_generated_files(str(rendered.directory), set(step_files)):
                warnings.append(f"Removing stale generated file {stale}")
                (self.s.workspace.path / Path(*stale.split("/"))).unlink()
                files[stale] = "deleted"
            policy_changed = any(
                path.endswith(".xml") and self.s.workspace.read(path) != content
                for path, content in step_files.items()
            )
            self.s.workspace.write(step_files)
            files.update({path: content for path, content in step_files.items()})
            compiled = self.s.compile(
                self.s.workspace.path / Path(*rendered.deployment.parameters_file.parts)
            )
            leaked = find_secret_literals(compiled.parameters)
            if leaked:
                raise ChangeError(
                    "Compiled parameters contain secret-shaped values: " + ", ".join(f.path for f in leaked)
                )
            template_hashes[str(rendered.deployment.template)] = compiled.template_hash
            spec = rendered.deployment
            depends_on_deploy = any(dep in deploy_ids for dep in change.depends_on)
            step = ChangeStep(
                id=change.step_id,
                kind=StepKind.DEPLOY,
                description=f"{change.intent.kind} {rendered.directory}",
                depends_on=list(change.depends_on),
                contract_dir=str(rendered.directory),
                template=str(spec.template),
                parameters_file=str(spec.parameters_file),
                location=spec.location,
                subscription_id=spec.subscription_id,
                deployment_name=f"{spec.name_base}-{stamp}"[:64],
                template_hash=compiled.template_hash,
                parameters_hash=compiled.parameters_hash,
                what_if_deferred=depends_on_deploy,
            )
            if not depends_on_deploy:
                report = self._what_if(step, compiled)
                if report.error and mode == ChangeMode.DIRECT.value:
                    raise ChangeError(f"What-if failed for {step.id}: {report.error}")
                if report.error:
                    warnings.append(
                        f"What-if for {step.id} failed ({report.error}); the pipeline will preview it."
                    )
                step = step.model_copy(
                    update={"what_if": _summarize_what_if(report, policy_changed=policy_changed)}
                )
            steps.append(step)

        for prerequisite in request.prerequisites:
            steps.append(
                ChangeStep(
                    id=prerequisite.step_id,
                    kind=StepKind.PREREQUISITE,
                    description=prerequisite.description,
                    depends_on=list(prerequisite.depends_on),
                    commands=list(prerequisite.commands),
                    verification=prerequisite.verification,
                )
            )

        for path, content in request.extra_files:
            if not path.startswith(EXTRA_FILE_PREFIXES) or ".." in path or "\\" in path:
                raise ChangeError(f"{path} cannot be part of a change set")
            self.s.workspace.write({path: content})
            files[path] = content

        loaded = self.s.authorizer.loaded
        change = ChangeSet(
            id=change_id,
            created_at=now,
            created_by=self.s.authorizer.caller.principal.label,
            environment=request.environment,
            environment_class=env.environment_class,
            mode=mode,
            summary=clean_text(request.summary),
            intents=[f"{intent_directory(c.intent)}/contract.yaml" for c in request.changes],
            files={
                path: ("deleted" if content == "deleted" else _sha256(content))
                for path, content in files.items()
            },
            steps=steps,
            repo_base_commit=base_commit,
            admin_policy_ref=loaded.ref,
            admin_policy_blob=loaded.blob_sha,
            compat=CompatibilityTuple(
                agent_version=self.s.agent_version,
                agent_upstream_commit=self.s.agent_lock.upstream.commit,
                repo_upstream_commit=repo_upstream,
                live_release=live,
                template_hashes=template_hashes,
            ),
            branch=branch,
            warnings=warnings,
        )
        self.s.store.save(change, {p: c for p, c in files.items() if c != "deleted"})
        prepared = PreparedChange(change=change, content_hash=change.content_hash())
        self.s.audit.record(
            "change.prepare",
            details={
                "change": change.id,
                "mode": change.mode,
                "environment": change.environment,
                "hash": prepared.content_hash,
            },
        )
        return prepared

    def _what_if(self, step: ChangeStep, compiled: CompiledDeployment) -> WhatIfReport:
        target = DeploymentTarget(
            scope="subscription", subscription_id=step.subscription_id or "", location=step.location
        )
        try:
            return self.s.runner_factory(step.subscription_id or "").what_if(
                target, step.deployment_name or "", compiled
            )
        except Exception as exc:
            return WhatIfReport(status="Failed", error=default_redactor().redact(str(exc))[:500])

    # ------------------------------------------------------------------ execute
    def _verify(self, change: ChangeSet, approved_hash: str) -> None:
        if approved_hash != change.content_hash():
            raise ChangeError("The approval does not match this change set (content hash differs)")
        if self.s.reload_policy is not None:
            current = self.s.reload_policy()
            if current.blob_sha != change.admin_policy_blob:
                raise ChangeError("The admin policy changed since this change was prepared; prepare it again")
        if self.s.agent_lock.upstream.commit != change.compat.agent_upstream_commit:
            raise ChangeError("The agent's upstream pin changed since preparation; prepare the change again")
        if self.s.workspace.base_commit() != change.repo_base_commit:
            raise ChangeError("The contracts repository moved since preparation; prepare the change again")
        repo = self.s.workspace.repository
        self.s.workspace.begin_branch(change.branch)
        if repo.upstream_commit() != change.compat.repo_upstream_commit:
            raise ChangeError(
                "The repository's upstream pin changed since preparation; prepare the change again"
            )
        snapshot = self.s.store.snapshot(change.id)
        for path, digest in change.files.items():
            if digest == "deleted":
                target = self.s.workspace.path / Path(*path.split("/"))
                if target.exists():
                    target.unlink()
                continue
            content = snapshot.get(path)
            if content is None or _sha256(content) != digest:
                raise ChangeError(f"Stored file {path} does not match the approved change set")
        self.s.workspace.write(
            {p: c for p, c in snapshot.items() if change.files.get(p) not in (None, "deleted")}
        )
        env = self._environment(change.environment)
        live = self.s.live_release(env)
        if change.compat.live_release is not None and live != change.compat.live_release:
            raise ChangeError("The gateway's release changed since preparation; prepare the change again")

    def execute(self, change_id: str, approved_hash: str) -> dict[str, Any]:
        """Execute an approved change set. Returns the final status.

        A change set runs at most once. One that failed can be executed again (deployments are
        idempotent); one that was already executed needs a new change set.
        """
        change = self.s.store.load(change_id)
        state = self.s.store.status(change_id).get("state")
        if state in EXECUTED_STATES:
            raise ChangeError(
                f"Change set {change_id} was already executed (state: {state}); prepare a new change instead"
            )
        try:
            self._verify(change, approved_hash)
        except ChangeError as exc:
            self.s.audit.record(
                "change.execute",
                outcome=AuditOutcome.DENIED,
                details={"change": change_id, "reason": str(exc)},
            )
            raise
        self.s.audit.record(
            "change.execute",
            outcome=AuditOutcome.APPROVED,
            details={"change": change_id, "mode": change.mode},
        )
        if change.mode == ChangeMode.DIRECT.value:
            return self._execute_direct(change)
        return self._record_change(change, executed_by="pipeline")

    def _execute_direct(self, change: ChangeSet) -> dict[str, Any]:
        for step in change.ordered_steps():
            if step.kind is StepKind.PREREQUISITE:
                self.s.store.record(change.id, "step.manual", step=step.id, status=StepStatus.MANUAL.value)
                continue
            compiled = self.s.compile(self.s.workspace.path / Path(*(step.parameters_file or "").split("/")))
            if (
                compiled.template_hash != step.template_hash
                or compiled.parameters_hash != step.parameters_hash
            ):
                raise ChangeError(f"Compiled output of {step.id} differs from the approved change set")
            report = self._what_if(step, compiled)
            if report.error:
                raise ChangeError(f"What-if failed for {step.id}: {report.error}")
            if step.what_if is not None and report.fingerprint() != step.what_if.fingerprint:
                raise ChangeError(
                    f"The predicted changes for {step.id} differ from what was approved; prepare again"
                )
            if step.what_if_deferred and report.counts().get("Delete"):
                raise ChangeError(
                    f"Deferred step {step.id} would delete resources; review and prepare it separately"
                )
            target = DeploymentTarget(
                scope="subscription", subscription_id=step.subscription_id or "", location=step.location
            )
            try:
                record = self.s.runner_factory(step.subscription_id or "").deploy(
                    target, step.deployment_name or "", compiled
                )
            except Exception as exc:
                message = default_redactor().redact(str(exc))[:1000]
                self.s.store.record(
                    change.id, "step.failed", step=step.id, status=StepStatus.FAILED.value, error=message
                )
                self.s.store.record(change.id, "change.failed", state="failed")
                self.s.audit.record(
                    "change.deploy",
                    outcome=AuditOutcome.ERROR,
                    details={"change": change.id, "step": step.id, "error": message},
                )
                raise ChangeError(f"Deployment of {step.id} failed: {message}") from exc
            error = default_redactor().redact(record.error)[:2000] if record.error else None
            outputs = _safe_outputs(record)
            self.s.store.record(
                change.id,
                "step.deployed" if record.succeeded else "step.failed",
                step=step.id,
                status=StepStatus.DEPLOYED.value if record.succeeded else StepStatus.FAILED.value,
                deployment=record.name,
                provisioningState=record.provisioning_state,
                correlationId=record.correlation_id,
                outputs=outputs,
                error=error,
            )
            self.s.audit.record(
                "change.deploy",
                outcome=AuditOutcome.OK if record.succeeded else AuditOutcome.ERROR,
                details={
                    "change": change.id,
                    "step": step.id,
                    "deployment": record.name,
                    "state": record.provisioning_state,
                },
            )
            if not record.succeeded:
                self.s.store.record(change.id, "change.failed", state="failed")
                raise ChangeError(
                    f"Deployment {record.name} failed: {record.error or record.provisioning_state}"
                )
        return self._record_change(change, executed_by="direct")

    def _record_change(self, change: ChangeSet, *, executed_by: str) -> dict[str, Any]:
        """Commit the files and manifest on the change branch and record them in the canonical repo.

        * Hosted repository with a git provider: push the branch and open a pull request (labelled
          ``deployed-directly`` when the change is already deployed).
        * Local canonical repository and a direct change: fast-forward its base branch, because there
          is no review platform and the repository must match what is deployed.
        * Otherwise: push the branch so someone can open a pull request.

        When recording fails after a direct deployment, the result says so prominently: Azure and
        the repository disagree until the commit reaches the base branch.
        """
        workspace = self.s.workspace
        manifest = change.model_copy(update={"executed_by": executed_by}).manifest()
        manifest_path = f"{CITADEL_DIR}/changesets/{change.id}.json"
        workspace.write({manifest_path: json.dumps(manifest, indent=2) + "\n"})
        paths = [*change.files.keys(), manifest_path]
        title = f"[citadel-agent] {change.summary}"
        commit = workspace.commit(title, paths, author=change.created_by)
        result: dict[str, Any] = {
            "change": change.id,
            "mode": change.mode,
            "commit": commit,
            "branch": change.branch,
        }
        policy = self.s.authorizer.policy
        direct = executed_by == "direct"
        try:
            if not workspace.has_remote():
                result["recorded"] = "local-branch"
                result["next"] = f"No remote is configured; the commit is on branch {change.branch}."
            elif workspace.remote_is_local() and direct:
                workspace.push_base()
                result["recorded"] = "base-branch"
            elif self.s.git_provider is not None and policy is not None and not workspace.remote_is_local():
                workspace.push(change.branch)
                labels = list(policy.gitops.labels) + (["deployed-directly"] if direct else [])
                pr = self.s.git_provider.open_pull_request(
                    branch=change.branch,
                    base=policy.gitops.base_branch,
                    title=title,
                    body=self._pull_request_body(change, executed_by),
                    labels=labels,
                    reviewers=list(policy.gitops.reviewers),
                )
                result["recorded"] = "pull-request"
                result["pullRequest"] = {"number": pr.number, "url": pr.url}
                if direct:
                    result["next"] = (
                        f"Merge pull request #{pr.number} so the contracts repository matches what is "
                        "deployed."
                    )
                    if self._environment(change.environment).direct_recording == "env-branch":
                        result["next"] += (
                            " (Environment-branch recording is not available yet, "
                            "so a pull request was used.)"
                        )
                else:
                    result["next"] = (
                        f"After review, merging pull request #{pr.number} deploys the change "
                        "through the pipeline."
                    )
            else:
                workspace.push(change.branch)
                result["recorded"] = "branch"
                result["next"] = (
                    f"Open a pull request from {change.branch} into {workspace.base_branch} "
                    "(no git provider is configured)."
                )
        except (CommandError, WorkspaceError, GitProviderError) as exc:
            message = default_redactor().redact(str(exc))[:500]
            result["recorded"] = "failed"
            result["recordError"] = message
            result["next"] = (
                f"The commit is only in the agent's working clone ({workspace.path}, branch "
                f"{change.branch}). Push or merge it manually"
                + (" - Azure already has this change." if direct else ".")
            )
            try:
                if workspace.has_remote():
                    workspace.push(change.branch)
                    result["next"] = (
                        f"Branch {change.branch} was pushed, but recording failed ({message}). "
                        f"Merge it into {workspace.base_branch}"
                        + (" - Azure already has this change." if direct else ".")
                    )
            except (CommandError, WorkspaceError):
                pass
        state = {
            "base-branch": "recorded",
            "pull-request": "recorded" if direct else "awaiting-merge",
            "branch": "branch-pushed",
            "local-branch": "committed-locally",
            "failed": "record-failed",
        }[result["recorded"]]
        self.s.store.record(
            change.id,
            "change.recorded",
            state=state,
            recordedCommit=commit,
            **{k: result[k] for k in ("pullRequest", "next", "recordError") if k in result},
        )
        self.s.audit.record(
            "change.record",
            outcome=AuditOutcome.ERROR if state == "record-failed" else AuditOutcome.OK,
            details=result,
        )
        return result

    @staticmethod
    def _pull_request_body(change: ChangeSet, executed_by: str) -> str:
        status = (
            "This change was **already deployed** to a dev/test environment after approval "
            "and is recorded here."
            if executed_by == "direct"
            else "Merging this pull request deploys the change through the `citadel-deploy` workflow."
        )
        lines = [
            f"Prepared by Citadel Agent for {change.created_by}.",
            "",
            status,
            "",
            f"* Change set: `{change.id}` (environment `{change.environment}`)",
            f"* Content hash: `{change.content_hash()}`",
            f"* Upstream commit: `{change.compat.repo_upstream_commit[:12]}`",
            "",
            "## Steps",
            "",
        ]
        for step in change.ordered_steps():
            if step.kind is StepKind.PREREQUISITE:
                lines.append(f"* `{step.id}` (manual prerequisite): {step.description}")
                lines.extend(f"  * `{command}`" for command in step.commands)
            else:
                counts = ", ".join(
                    f"{k} {v}" for k, v in sorted((step.what_if.counts if step.what_if else {}).items())
                )
                lines.append(f"* `{step.id}`: `{step.parameters_file}` (what-if: {counts or 'deferred'})")
        if change.warnings:
            lines += ["", "## Warnings", ""] + [f"* {w}" for w in change.warnings]
        return "\n".join(lines)


def default_policy_reloader(workspace: CanonicalWorkspace, base_branch: str) -> Callable[[], LoadedPolicy]:
    return lambda: load_admin_policy(workspace.path, base_branch=base_branch)
