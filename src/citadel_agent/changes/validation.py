_USING = re.compile(r"^\s*using\s+'(?P<path>[^']+)'", re.MULTILINE)
_TEXT_SUFFIXES = {".yaml", ".yml", ".json", ".xml", ".bicepparam", ".md", ".txt"}
_PARAMS_FILE = re.compile(
    r"^contracts/(?:access|backend|publish|alerts)/(?:[A-Za-z0-9._-]+/)+main\.bicepparam$"
)
_GUID = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")
_LOCATION = re.compile(r"^[a-z0-9]{3,30}$")


def step_problems(
    repo_root: Path,
    upstream_path: str,
    *,
    parameters_file: str,
    template: str,
    subscription_id: str,
    location: str,
    check_file: bool = True,
) -> list[str]:
    """Reasons a change-set deploy step must not run with credentials.

    A change-set manifest is data a pull request controls, and the what-if and deploy jobs run with
    cloud credentials. A step may only deploy a generated ``contracts/<kind>/.../main.bicepparam``
    that points at an upstream template, so a manifest cannot make the pipeline compile or deploy
    anything else.
    """
    problems: list[str] = []
    if ".." in PurePosixPath(parameters_file).parts or not _PARAMS_FILE.match(parameters_file):
        problems.append(
            f"parametersFile '{parameters_file}' is not a generated contracts/<kind>/.../main.bicepparam"
        )
    prefix = f"{upstream_path.rstrip('/')}/bicep/infra/"
    if ".." in PurePosixPath(template).parts or not (
        template.startswith(prefix) and template.endswith("/main.bicep")
    ):
        problems.append(f"template '{template}' is not an upstream contract template under {prefix}")
    if not _GUID.match(subscription_id or ""):
        problems.append("subscriptionId is not a GUID")
    if not _LOCATION.match(location or ""):
        problems.append("location is not a plain Azure region name")
    if problems or not check_file:
        return problems
    file = repo_root / Path(*parameters_file.split("/"))
    if not file.is_file():
        return [f"parametersFile '{parameters_file}' does not exist"]
    text = file.read_text(encoding="utf-8")
    if GENERATED_NOTICE not in "\n".join(text.splitlines()[:3]):
        problems.append(f"'{parameters_file}' is not a file generated by citadel-agent")
    using = _USING.search(text)
    resolved = (
        posixpath.normpath(posixpath.join(posixpath.dirname(parameters_file), using["path"])) if using else ""
    )
    if resolved != template:
        problems.append(f"'{parameters_file}' does not use the template '{template}'")
    return problems


def _stray_files(repo: CanonicalRepository) -> list[str]:
    """Templates and Bicep configuration outside the pinned upstream: nothing may add code to compile."""
    found: list[str] = []
    upstream = Path(*repo.upstream_path.parts)
    for folder, dirs, files in os.walk(repo.root):
        relative = Path(folder).relative_to(repo.root)
        dirs[:] = [d for d in dirs if d != ".git" and (relative / d) != upstream]
        for name in files:
            path = (relative / name).as_posix()
            is_template = name.endswith(".bicep") or name.lower() == "bicepconfig.json"
            stray_parameters = name.endswith(".bicepparam") and not path.startswith(f"{CONTRACTS_DIR}/")
            if is_template or stray_parameters:
                found.append(path)
    return sorted(found)


class IssueLevel(StrEnum):
    ERROR = "error"
    WARNING = "warning"


@dataclass(frozen=True)
class ValidationIssue:
    level: IssueLevel
    path: str
    message: str

    def __str__(self) -> str:
        return f"{self.level.value}: {self.path}: {self.message}"


def _sha256(text: str) -> str:
    return "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()


def _active_rotations(repo: CanonicalRepository) -> set[str]:
    """Contract directories with a rotation transaction in its 'rotate' phase."""
    active: set[str] = set()
    folder = repo.path(ROTATIONS_DIR)
    if folder.is_dir():
        for file in folder.glob("*.json"):
            try:
                data = json.loads(file.read_text(encoding="utf-8"))
            except ValueError:
                continue
            if data.get("phase") == "rotate" and data.get("contractDir"):
                active.add(str(data["contractDir"]))
    return active


def validate_repository(
    repo: CanonicalRepository,
    loaded: LoadedPolicy,
    *,
    compile_contracts: bool = False,
    compile_fn: Callable[[Path], CompiledDeployment] = compile_deployment,
) -> list[ValidationIssue]:
    """Return every problem found in the repository (empty when valid)."""
    issues: list[ValidationIssue] = []

    def error(path: str, message: str) -> None:
        issues.append(ValidationIssue(IssueLevel.ERROR, path, message))

    if loaded.policy is None:
        error(".citadel/admin-policy.yaml", loaded.error or "admin policy unavailable")
        return issues
    policy = loaded.policy
    upstream_prefix = str(repo.upstream_path) + "/"
    contracts_root = repo.path(CONTRACTS_DIR)

    # Nothing outside the pinned upstream may add a template, Bicep configuration or parameter file.
    for stray in _stray_files(repo):
        error(
            stray, "templates are not allowed outside upstream/ (also bicepconfig.json and parameter files)"
        )

    # Change-set manifests may only hold JSON.
    manifests_dir = repo.path(PurePosixPath(CITADEL_DIR) / "changesets")
    for other in sorted(manifests_dir.iterdir()) if manifests_dir.is_dir() else []:
        if other.is_file() and other.suffix != ".json" and other.name != ".gitkeep":
            error(other.relative_to(repo.root).as_posix(), "only .json change-set manifests are allowed")

    # Secret scan of every text file in contracts/ and .citadel/.
    scanner = Redactor()
    for base in (contracts_root, repo.path(CITADEL_DIR)):
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if path.is_file() and path.suffix in _TEXT_SUFFIXES:
                text = path.read_text(encoding="utf-8", errors="replace")
                if scanner.redact(text) != text:
                    error(path.relative_to(repo.root).as_posix(), "contains a secret-shaped value")

    rotating = _active_rotations(repo)
    expected_steps: dict[str, tuple[str, str, str]] = {}
    secret_owners: dict[tuple[str, str], str] = {}
    upstream_commit = ""
    try:
        upstream_commit = repo.upstream_commit()
    except Exception:
        error(str(repo.upstream_path), "upstream submodule is not checked out")
        return issues

    for relative in repo.iter_intent_files():
        rel = str(relative)
        try:
            intent = load_intent(repo.path(relative))
        except (ValidationError, ValueError) as exc:
            error(rel, f"invalid intent: {exc}")
            continue
        if intent.environment not in policy.environments:
            error(rel, f"environment '{intent.environment}' is not defined in the admin policy")
            continue
        env = policy.environment(intent.environment)
        for problem in cap_violations(intent, env.caps):
            error(rel, problem)
        if isinstance(intent, AccessContractIntent) and env.key_vault is not None:
            vault = env.key_vault.name.lower()
            for secret in sorted(intent.key_vault_secret_names()):
                owner = secret_owners.setdefault((vault, secret), rel)
                if owner != rel:
                    error(rel, f"Key Vault secret '{secret}' in '{vault}' is also written by {owner}")
        if (
            isinstance(intent, AccessContractIntent)
            and intent.key_rotation.key_rotation_enabled
            and str(relative.parent) not in rotating
        ):
            error(rel, "keyRotationEnabled may only be true during an active rotation transaction")

        try:
            rendered = render_intent(
                intent,
                RenderContext(
                    repo_root=repo.root,
                    upstream_root=repo.upstream_root,
                    target=env.to_target(intent.environment),
                    upstream_commit=upstream_commit,
                ),
            )
        except (RenderError, ValueError) as exc:
            error(rel, f"cannot render: {exc}")
            continue
        deployment = rendered.deployment
        expected_steps[deployment.parameters_file.as_posix()] = (
            deployment.template.as_posix(),
            deployment.subscription_id,
            deployment.location,
        )
        for path, content in rendered.files.items():
            if path.name == "contract.yaml":
                continue
            on_disk = repo.path(path)
            if not on_disk.is_file():
                error(
                    str(path), "generated file is missing; regenerate with 'citadel-agent contracts render'"
                )
            elif on_disk.read_text(encoding="utf-8") != content:
                error(str(path), "generated file is out of date or was edited by hand; regenerate it")

        params_file = repo.path(rendered.deployment.parameters_file)
        if params_file.is_file():
            match = _USING.search(params_file.read_text(encoding="utf-8"))
            target = (
                posixpath.normpath(posixpath.join(str(rendered.directory), match["path"])) if match else ""
            )
            if not target.startswith(upstream_prefix):
                error(
                    str(rendered.deployment.parameters_file),
                    "the 'using' path must point into the upstream submodule",
                )
        for path in repo.path(rendered.directory).glob("*.xml"):
            for issue in lint_policy(path.read_text(encoding="utf-8")):
                level = IssueLevel.ERROR if issue.level is LintLevel.ERROR else IssueLevel.WARNING
                issues.append(ValidationIssue(level, path.relative_to(repo.root).as_posix(), issue.message))

        if compile_contracts and params_file.is_file():
            try:
                compile_fn(params_file)
            except BicepCompileError as exc:
                error(str(rendered.deployment.parameters_file), f"does not compile: {exc}")

    # Change-set manifests must match the files they describe. A later change set supersedes an
    # earlier one for the files it touches, so only the newest manifest per file is checked
    # (otherwise a contract first deployed through a pull request could never change again).
    changesets = repo.path(PurePosixPath(CITADEL_DIR) / "changesets")
    manifests: list[tuple[str, str, dict[str, Any]]] = []
    for manifest_path in sorted(changesets.glob("*.json")) if changesets.is_dir() else []:
        rel = manifest_path.relative_to(repo.root).as_posix()
        try:
            manifests.append((rel, manifest_path.stem, json.loads(manifest_path.read_text(encoding="utf-8"))))
        except ValueError as exc:
            error(rel, f"invalid JSON: {exc}")
    newest: dict[str, str] = {}
    for _, change_id, manifest in manifests:
        for path in manifest.get("files") or {}:
            newest[path] = max(newest.get(path, change_id), change_id)
    for rel, change_id, manifest in manifests:
        files = manifest.get("files") or {}
        # A manifest can still run unless every file it describes was superseded or deleted. One that
        # describes no files is never historical: it is exactly what an attacker would submit.
        live = not files or any(newest[p] == change_id for p in files)
        if live and manifest.get("environment") not in policy.environments:
            error(rel, f"environment '{manifest.get('environment')}' is not defined in the admin policy")
        for step in manifest.get("steps") or []:
            if not isinstance(step, dict) or step.get("kind") != "deploy":
                continue
            values = {
                "parameters_file": str(step.get("parametersFile") or ""),
                "template": str(step.get("template") or ""),
                "subscription_id": str(step.get("subscriptionId") or ""),
                "location": str(step.get("location") or ""),
            }
            label = f"step {step.get('id')}"
            for problem in step_problems(repo.root, str(repo.upstream_path), check_file=live, **values):
                error(rel, f"{label}: {problem}")
            if live:
                want = expected_steps.get(values["parameters_file"])
                got = (values["template"], values["subscription_id"], values["location"])
                if want is None:
                    error(
                        rel,
                        f"{label} deploys '{values['parameters_file']}', which is not a rendered contract",
                    )
                elif want != got:
                    error(
                        rel,
                        f"{label} differs from the rendered contract (template, subscription or location)",
                    )
    for rel, change_id, manifest in manifests:
        if manifest.get("executedBy") == "direct":
            continue
        for path, digest in (manifest.get("files") or {}).items():
            if newest[path] != change_id:
                continue
            current = repo.path(path)
            if digest == "deleted":
                if current.exists():
                    error(rel, f"{path} should have been deleted")
            elif not current.is_file() or _sha256(current.read_text(encoding="utf-8")) != digest:
                error(rel, f"{path} differs from the prepared change set; prepare the change again")
    return issues
