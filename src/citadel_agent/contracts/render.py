"""Render contract intents into the files upstream Citadel templates consume.

Each intent renders to ``main.bicepparam`` (plus product-policy XML for access contracts) next to
its ``contract.yaml`` in the canonical contracts repository. Parameter files reference the upstream
templates through a relative ``using`` path into the repository's pinned upstream submodule, so the
exact same files are deployed in direct mode and by the repository's CI/CD pipeline.
"""

from __future__ import annotations

import posixpath
import re
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, Literal

from citadel_agent.contracts.access import AccessContractIntent
from citadel_agent.contracts.alerts import AlertsIntent
from citadel_agent.contracts.backend import BackendContractIntent
from citadel_agent.contracts.bicepparam import BicepExpression, load_text_content, render_param_file
from citadel_agent.contracts.intent_io import ContractIntent, dump_intent, intent_directory
from citadel_agent.contracts.policy_builder import PolicyBuildContext, build_product_policy
from citadel_agent.contracts.publish import PublishContractIntent
from citadel_agent.contracts.targets import EnvironmentTarget
from citadel_agent.upstream.layout import UpstreamLayout

PARAMETERS_FILE_NAME = "main.bicepparam"
PLACEHOLDER_SUBSCRIPTION = "00000000-0000-0000-0000-000000000000"
GENERATED_NOTICE = "Generated by citadel-agent from contract.yaml. Do not edit: change the contract intent."


class RenderError(ValueError):
    """Raised when an intent cannot be rendered for the target environment."""


@dataclass(frozen=True)
class DeploymentSpec:
    """How a rendered contract is deployed (all Citadel contract templates are subscription scoped)."""

    kind: Literal["access", "backend", "publish", "alerts"]
    template: PurePosixPath
    parameters_file: PurePosixPath
    location: str
    subscription_id: str
    name_base: str
    scope: Literal["subscription"] = "subscription"


@dataclass(frozen=True)
class RenderedContract:
    """Files produced for one intent, keyed by repository-relative path."""

    directory: PurePosixPath
    files: dict[PurePosixPath, str]
    deployment: DeploymentSpec

    def write(self, repo_root: Path) -> list[Path]:
        """Write all files under ``repo_root`` with LF line endings and return their paths."""
        written: list[Path] = []
        for relative, content in sorted(self.files.items()):
            path = repo_root / Path(*relative.parts)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            written.append(path)
        return written


@dataclass(frozen=True)
class RenderContext:
    """Where the canonical repository and its upstream submodule live, and the target environment."""

    repo_root: Path
    upstream_root: Path
    target: EnvironmentTarget
    upstream_commit: str = ""

    @property
    def layout(self) -> UpstreamLayout:
        return UpstreamLayout(self.upstream_root)

    def repo_relative(self, path: Path) -> PurePosixPath:
        try:
            return PurePosixPath(path.resolve().relative_to(self.repo_root.resolve()).as_posix())
        except ValueError as exc:
            raise RenderError(f"{path} is not inside the repository {self.repo_root}") from exc


def _using_path(ctx: RenderContext, directory: PurePosixPath, template: Path) -> str:
    # posixpath keeps forward slashes on every OS; Bicep rejects '\' in paths (BCP098).
    template_rel = ctx.repo_relative(template)
    return posixpath.relpath(template_rel.as_posix(), directory.as_posix())


def _header(ctx: RenderContext, template_rel: PurePosixPath, kind: str) -> list[str]:
    commit = ctx.upstream_commit[:12] if ctx.upstream_commit else "unknown"
    return [
        GENERATED_NOTICE,
        f"Contract kind: {kind}. Environment: {ctx.target.name} ({ctx.target.environment_class}).",
        f"Upstream template: {template_rel.as_posix()} (upstream commit {commit}).",
    ]


def _slug(*parts: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", "-".join(parts).lower()).strip("-")


def _key_vault_param(intent: AccessContractIntent, target: EnvironmentTarget) -> dict[str, Any]:
    if target.key_vault is not None:
        return target.key_vault.to_param()
    if intent.store_credentials_in_key_vault:
        raise RenderError(
            f"Environment '{target.name}' has no Key Vault configured, but the contract stores keys there"
        )
    return {
        "subscriptionId": PLACEHOLDER_SUBSCRIPTION,
        "resourceGroupName": "placeholder",
        "name": "placeholder",
    }


def _foundry_config(intent: AccessContractIntent) -> dict[str, Any]:
    f = intent.foundry
    # Upstream foundryConfig keys are mapped explicitly: two do not follow camelCase (…APIVersion).
    return {
        "connectionNamePrefix": f.connection_name_prefix,
        "connectionCategory": f.connection_category,
        "authType": f.auth_type,
        "managedIdentityAudience": f.managed_identity_audience,
        "deploymentInPath": "true" if f.deployment_in_path else "false",
        "isSharedToAll": f.is_shared_to_all,
        "inferenceAPIVersion": f.inference_api_version,
        "deploymentAPIVersion": f.deployment_api_version,
        "staticModels": list(f.static_models),
        "listModelsEndpoint": f.list_models_endpoint,
        "getModelEndpoint": f.get_model_endpoint,
        "deploymentProvider": f.deployment_provider,
        "customHeaders": dict(f.custom_headers),
        "authConfig": {},
    }


def _render_access(intent: AccessContractIntent, ctx: RenderContext) -> RenderedContract:
    directory = intent_directory(intent)
    template = ctx.layout.access_contract_template
    files: dict[PurePosixPath, str] = {}
    policy_ctx = PolicyBuildContext(
        foundry_managed_identity=intent.foundry.enabled
        and intent.foundry.auth_type == "ProjectManagedIdentity",
        foundry_audience=intent.foundry.managed_identity_audience,
        tenant_id=ctx.target.tenant_id,
    )
    services: list[dict[str, Any]] = []
    for service in intent.services:
        if service.policy_xml_file:
            policy_file = service.policy_xml_file
        else:
            policy_file = f"{service.code.lower()}-product-policy.xml"
            files[directory / policy_file] = build_product_policy(service, policy_ctx)
        entry: dict[str, Any] = {"code": service.code, "apiKeySecretName": service.key_secret_name}
        if service.endpoint_secret_name:
            entry["endpointSecretName"] = service.endpoint_secret_name
        if service.asset_endpoints:
            entry["assetEndpoints"] = [e.to_param() for e in service.asset_endpoints]
        if service.publish_all_asset_endpoints:
            entry["publishAllAssetEndpoints"] = True
        if service.foundry_api_name:
            entry["foundryApiName"] = service.foundry_api_name
        entry["policyXml"] = load_text_content(policy_file)
        services.append(entry)

    params: dict[str, Any] = {
        "apim": ctx.target.apim.to_param(),
        "keyVault": _key_vault_param(intent, ctx.target),
        "useTargetAzureKeyVault": intent.store_credentials_in_key_vault,
        "useCase": intent.use_case.to_param(),
        "apiNameMapping": {s.code: list(s.apis) for s in intent.services},
        "services": services,
        "productTerms": intent.product_terms,
        "usePrimaryKey": intent.key_rotation.use_primary_key,
        "keyRotationEnabled": intent.key_rotation.key_rotation_enabled,
        "useTargetFoundry": intent.foundry.enabled,
    }
    if intent.foundry.enabled and intent.foundry.project is not None:
        params["foundry"] = intent.foundry.project.to_param()
        params["foundryConfig"] = _foundry_config(intent)
    resiliency = intent.resiliency
    if resiliency.global_gateway_url:
        params["globalGatewayUrl"] = resiliency.global_gateway_url
    if resiliency.additional_apim_gateways:
        params["additionalApimGateways"] = [g.to_param() for g in resiliency.additional_apim_gateways]
    if resiliency.additional_key_vaults:
        params["additionalKeyVaults"] = [k.to_param() for k in resiliency.additional_key_vaults]
    if resiliency.additional_foundries:
        params["additionalFoundries"] = [f.to_param() for f in resiliency.additional_foundries]
    params.update(intent.extra_parameters)

    return _finish(
        intent,
        ctx,
        directory,
        template,
        params,
        files,
        "access",
        _slug("citadel-access", intent.use_case.postfix),
    )


def _render_backend(intent: BackendContractIntent, ctx: RenderContext) -> RenderedContract:
    target = ctx.target
    if target.apim_managed_identity is None:
        raise RenderError(f"Environment '{target.name}' has no APIM managed identity configured")
    identity = target.apim_managed_identity
    params: dict[str, Any] = {
        "apim": target.apim.to_param(),
        "apimManagedIdentity": {
            "subscriptionId": identity.subscription_id,
            "resourceGroupName": identity.resource_group_name,
            "name": identity.name,
        },
        "llmBackendConfig": [b.to_param() for b in intent.backends],
        "configureCircuitBreaker": intent.circuit_breaker_enabled,
        "configureSessionAffinity": intent.session_affinity_enabled,
        "modelAliases": [a.to_param() for a in intent.model_aliases],
    }
    if intent.circuit_breaker_defaults is not None:
        params["circuitBreakerDefaults"] = intent.circuit_breaker_defaults.to_param()
    if intent.session_affinity_defaults is not None:
        params["sessionAffinityDefaults"] = dict(intent.session_affinity_defaults)
    if intent.anthropic_version:
        params["anthropicVersion"] = intent.anthropic_version
    uses_key_vault = any(b.auth_config and b.auth_config.key_vault_secret_uri for b in intent.backends)
    if uses_key_vault and target.key_vault is not None:
        params["keyVaultName"] = target.key_vault.name
    params.update(intent.extra_parameters)
    directory = intent_directory(intent)
    template = ctx.layout.backend_contract_template
    return _finish(
        intent, ctx, directory, template, params, {}, "backend", _slug("citadel-backend", intent.environment)
    )


def _render_publish(intent: PublishContractIntent, ctx: RenderContext) -> RenderedContract:
    target = ctx.target
    assets: list[dict[str, Any]] = []
    for asset in intent.assets:
        entry = asset.to_param()
        policy_file = entry.pop("policyXmlFile", None)
        if policy_file:
            entry["policyXml"] = load_text_content(policy_file)
        assets.append(entry)
    params: dict[str, Any] = {
        "apim": target.apim.to_param(),
        "managedIdentityClientId": (target.apim_managed_identity.client_id or "")
        if target.apim_managed_identity
        else "",
        "configureCircuitBreaker": intent.configure_circuit_breaker,
        "ensureUsageFragments": intent.ensure_usage_fragments,
        "useAssetTypePathPrefix": intent.use_asset_type_path_prefix,
        "publishAssets": assets,
    }
    if intent.circuit_breaker_defaults is not None:
        params["circuitBreakerDefaults"] = intent.circuit_breaker_defaults.to_param()
    if intent.api_center is not None:
        params["apiCenter"] = intent.api_center.to_param()
    params.update(intent.extra_parameters)
    directory = intent_directory(intent)
    template = ctx.layout.publish_contract_template
    name = _slug("citadel-publish", intent.name, intent.environment)
    return _finish(intent, ctx, directory, template, params, {}, "publish", name)


def _render_alerts(intent: AlertsIntent, ctx: RenderContext) -> RenderedContract:
    target = ctx.target
    if target.app_insights is None:
        raise RenderError(f"Environment '{target.name}' has no Application Insights component configured")
    params: dict[str, Any] = {
        "appInsights": target.app_insights.to_param(),
        "alertEmailAddress": intent.alert_email_address,
        "additionalEmailReceivers": [r.to_param() for r in intent.additional_email_receivers],
        "productNameFilter": intent.product_display_name_filter,
        "alertMode": intent.alert_mode,
        "namePrefix": intent.effective_name_prefix,
        "actionGroupShortName": intent.action_group_short_name,
        "alertsEnabled": intent.alerts_enabled,
        "alerts": [a.to_param() for a in intent.alerts],
    }
    params.update(intent.extra_parameters)
    directory = intent_directory(intent)
    template = ctx.layout.alerts_template
    name = _slug("citadel-alerts", intent.scope_name, intent.environment)
    return _finish(intent, ctx, directory, template, params, {}, "alerts", name)


def _finish(
    intent: ContractIntent,
    ctx: RenderContext,
    directory: PurePosixPath,
    template: Path,
    params: dict[str, Any],
    files: dict[PurePosixPath, str],
    kind: Literal["access", "backend", "publish", "alerts"],
    name_base: str,
) -> RenderedContract:
    if intent.environment != ctx.target.name:
        raise RenderError(
            f"Intent targets environment '{intent.environment}' but the context is '{ctx.target.name}'"
        )
    if not template.is_file():
        raise RenderError(f"Upstream template not found: {template}")
    template_rel = ctx.repo_relative(template)
    parameters_path = directory / PARAMETERS_FILE_NAME
    files = dict(files)
    files[parameters_path] = render_param_file(
        _using_path(ctx, directory, template), params, _header(ctx, template_rel, kind)
    )
    files[directory / "contract.yaml"] = dump_intent(intent)
    return RenderedContract(
        directory=directory,
        files=files,
        deployment=DeploymentSpec(
            kind=kind,
            template=template_rel,
            parameters_file=parameters_path,
            location=ctx.target.location,
            subscription_id=ctx.target.subscription_id,
            name_base=name_base[:50].rstrip("-"),
        ),
    )


def render_intent(intent: ContractIntent, ctx: RenderContext) -> RenderedContract:
    """Render an intent for the context's target environment."""
    if isinstance(intent, AccessContractIntent):
        return _render_access(intent, ctx)
    if isinstance(intent, BackendContractIntent):
        return _render_backend(intent, ctx)
    if isinstance(intent, PublishContractIntent):
        return _render_publish(intent, ctx)
    if isinstance(intent, AlertsIntent):
        return _render_alerts(intent, ctx)
    raise RenderError(f"Unsupported intent type: {type(intent).__name__}")


