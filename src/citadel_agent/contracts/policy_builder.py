"""Render APIM product policies for access contracts from a :class:`ProductPolicyIntent`.

The generated XML mirrors the upstream Citadel policy catalog
(``bicep/infra/citadel-access-contracts/citadel-access-contracts-policy.md``) and uses APIM's
``rawxml`` syntax, as the upstream access-contract module does. Product policies run before the
API-level policies, so most controls are expressed as variables that upstream fragments
(``security-handler``, ``validate-model-access``, ``raise-alert-events``) read later.
"""

from __future__ import annotations

from dataclasses import dataclass

from citadel_agent.contracts.access import (
    DEFAULT_FOUNDRY_AUDIENCE,
    AlertToggles,
    CallLimit,
    ContentSafetyPolicy,
    PiiPolicy,
    ProductPolicyIntent,
    ServiceIntent,
    TokenLimit,
    UsageDimension,
)

GENERATED_HEADER = (
    "<!-- Generated by citadel-agent from contract.yaml. Do not edit by hand: change the contract intent. -->"
)
JWT_TENANT_NAMED_VALUE = "{{JWT-TenantId}}"

_ALERT_VARIABLES: tuple[tuple[str, str], ...] = (
    ("throttling", "alertOnThrottling"),
    ("quota_exceeded", "alertOnQuotaExceeded"),
    ("backend_failure", "alertOnBackendFailure"),
    ("auth_failure", "alertOnAuthFailure"),
    ("content_safety", "alertOnContentSafety"),
    ("pii_failure", "alertOnPiiFailure"),
)
_DEFAULT_ALERTS = AlertToggles()
_DEFAULT_PII = PiiPolicy()

# Response body for PII blocking (matches the upstream policy catalog's PII_DETECTED error).
_PII_BLOCK_RESPONSE_BODY = "".join(
    [
        "@{ ",
        'var mappings = JArray.Parse(context.Variables.GetValueOrDefault<string>("piiMappings", "[]")); ',
        "var categories = new HashSet<string>(); ",
        "foreach (var mapping in mappings) { ",
        "categories.Add(mapping[\"placeholder\"].ToString().TrimStart('<').Split('_')[0]); } ",
        'return new JObject(new JProperty("error", new JObject(',
        'new JProperty("code", "PII_DETECTED"), ',
        'new JProperty("message", "Request blocked: Personal Identifiable Information (PII) ',
        'detected in the request."), ',
        'new JProperty("detectedCategories", string.Join(", ", categories)), ',
        'new JProperty("entityCount", mappings.Count)))).ToString(); }',
    ]
)


class PolicyBuildError(ValueError):
    """Raised when an intent cannot be expressed as a consistent product policy."""


@dataclass(frozen=True)
class PolicyBuildContext:
    """Contract-level facts the product policy depends on (beyond the service intent itself)."""

    foundry_managed_identity: bool = False
    foundry_audience: str = DEFAULT_FOUNDRY_AUDIENCE
    tenant_id: str | None = None


def _attr(value: str) -> str:
    """Escape a plain (non-expression) attribute value."""
    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


class _Writer:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.level = 0

    def line(self, text: str) -> None:
        self.lines.append("    " * self.level + text)

    def open(self, text: str) -> None:
        self.line(text)
        self.level += 1

    def close(self, text: str) -> None:
        self.level -= 1
        self.line(text)

    def variable(self, name: str, value: str) -> None:
        self.line(f'<set-variable name="{name}" value="{_attr(value)}" />')

    def expression_variable(self, name: str, expression: str) -> None:
        # Expressions are emitted verbatim (rawxml); callers only pass fixed templates and
        # validated tokens.
        self.line(f'<set-variable name="{name}" value="{expression}" />')

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def _bool(value: bool) -> str:
    return "true" if value else "false"


def _check_conflicts(policy: ProductPolicyIntent, ctx: PolicyBuildContext) -> None:
    if not ctx.foundry_managed_identity:
        return
    jwt = policy.jwt
    if jwt.audience and jwt.audience != ctx.foundry_audience:
        raise PolicyBuildError(
            "The Foundry connection uses ProjectManagedIdentity, which requires JWT audience "
            f"'{ctx.foundry_audience}'. Remove the custom JWT audience or switch the connection to ApiKey."
        )
    if jwt.issuer or jwt.openid_config_url:
        raise PolicyBuildError(
            "Custom JWT issuer/OpenID settings cannot be combined with a ProjectManagedIdentity connection."
        )
    if jwt.required_roles:
        raise PolicyBuildError(
            "requiredRoles cannot be combined with a ProjectManagedIdentity Foundry connection "
            "(managed identity tokens for the Foundry audience do not carry gateway app roles)."
        )


def _emit_authentication(w: _Writer, policy: ProductPolicyIntent, ctx: PolicyBuildContext) -> None:
    if ctx.foundry_managed_identity:
        tenant = ctx.tenant_id or JWT_TENANT_NAMED_VALUE
        w.line("<!-- Foundry ProjectManagedIdentity: validate the project managed identity token -->")
        w.variable("jwtRequired", "true")
        w.variable("jwtAudience", ctx.foundry_audience)
        w.variable("jwtIssuer", f"https://sts.windows.net/{tenant}/")
        w.variable(
            "jwtOpenIdConfigUrl",
            f"https://login.microsoftonline.com/{tenant}/v2.0/.well-known/openid-configuration",
        )
        return
    jwt = policy.jwt
    if not (jwt.required or jwt.audience or jwt.issuer or jwt.openid_config_url or jwt.required_roles):
        return
    w.line("<!-- Microsoft Entra ID / OIDC JWT validation (in addition to the api-key subscription key) -->")
    if jwt.required or jwt.required_roles:
        w.variable("jwtRequired", "true")
    if jwt.audience:
        w.variable("jwtAudience", jwt.audience)
    if jwt.issuer:
        w.variable("jwtIssuer", jwt.issuer)
    if jwt.openid_config_url:
        w.variable("jwtOpenIdConfigUrl", jwt.openid_config_url)
    if jwt.required_roles:
        w.variable("requiredRoles", ",".join(jwt.required_roles))


def _emit_alerts(w: _Writer, alerts: AlertToggles) -> None:
    changes: list[tuple[str, bool]] = []
    if alerts.enabled != _DEFAULT_ALERTS.enabled:
        changes.append(("alertsEnabled", alerts.enabled))
    for attribute, variable in _ALERT_VARIABLES:
        value = getattr(alerts, attribute)
        if value != getattr(_DEFAULT_ALERTS, attribute):
            changes.append((variable, value))
    if changes:
        w.line("<!-- Alert toggles that differ from the gateway defaults -->")
        for variable, value in changes:
            w.variable(variable, _bool(value))


def _emit_dimension(w: _Writer, name: str, dimension: UsageDimension | None) -> None:
    if dimension is None:
        return
    if dimension.header:
        w.expression_variable(
            name, f'@(context.Request.Headers.GetValueOrDefault("{dimension.header}", "{dimension.default}"))'
        )
    elif dimension.static_value is not None:
        w.variable(name, dimension.static_value)


def _emit_content_safety(w: _Writer, safety: ContentSafetyPolicy) -> None:
    if not safety.enabled:
        return
    w.line("<!-- Content safety: blocked content returns 403 -->")
    w.open(
        '<llm-content-safety backend-id="content-safety-backend" '
        f'shield-prompt="{_bool(safety.shield_prompt)}" window-size="1000" window-overlap-size="200" '
        f'enforce-on-completions="{_bool(safety.enforce_on_completions)}">'
    )
    w.open('<categories output-type="EightSeverityLevels">')
    for category, threshold in sorted(safety.thresholds.items()):
        w.line(f'<category name="{category}" threshold="{threshold}" />')
    w.close("</categories>")
    w.close("</llm-content-safety>")


def _token_limit_element(limit: TokenLimit, counter_expression: str) -> str:
    attributes = [
        f'counter-key="{counter_expression}"',
        f'tokens-per-minute="{limit.tokens_per_minute}"',
        f'estimate-prompt-tokens="{_bool(limit.estimate_prompt_tokens)}"',
        'tokens-consumed-header-name="consumed-tokens"',
        'remaining-tokens-header-name="remaining-tokens"',
        'retry-after-header-name="retry-after"',
    ]
    if limit.token_quota is not None and limit.token_quota_period is not None:
        attributes.append(f'token-quota="{limit.token_quota}"')
        attributes.append(f'token-quota-period="{limit.token_quota_period}"')
    return "<llm-token-limit " + " ".join(attributes) + " />"


def _emit_token_limits(w: _Writer, policy: ProductPolicyIntent) -> None:
    if policy.model_token_limits:
        w.line("<!-- Capacity per model (counter keys use normalized model names) -->")
        w.open("<choose>")
        for limit in policy.model_token_limits:
            model = limit.model.lower()
            w.open(
                '<when condition="@(context.Variables.GetValueOrDefault<string>("requestedModel", "")'
                f'.ToLowerInvariant() == "{model}")">'
            )
            w.line(_token_limit_element(limit, f'@(context.Subscription.Id + "-{model}")'))
            w.close("</when>")
        if policy.token_limit is not None:
            w.open("<otherwise>")
            w.line(_token_limit_element(policy.token_limit, '@(context.Subscription.Id + "-default")'))
            w.close("</otherwise>")
        w.close("</choose>")
    elif policy.token_limit is not None:
        w.line("<!-- Capacity: tokens per minute and long-term token quota for this subscription -->")
        w.line(_token_limit_element(policy.token_limit, "@(context.Subscription.Id)"))


def _regex_patterns_expression(pii: PiiPolicy) -> str:
    entries = []
    for item in pii.regex_patterns:
        pattern = item.pattern.replace('"', '""')
        entries.append(f'new JObject {{ ["pattern"] = @"{pattern}", ["category"] = "{item.category}" }}')
    return "@{ var patterns = new JArray { " + ", ".join(entries) + " }; return patterns.ToString(); }"


def _emit_pii_inbound(w: _Writer, pii: PiiPolicy) -> None:
    if pii.mode == "off":
        return
    if pii.mode == "block":
        w.line("<!-- PII blocking: requests containing PII are rejected with 400 PII_DETECTED -->")
        w.variable("piiBlockingEnabled", "true")
    else:
        w.line("<!-- PII anonymization: PII is masked before the backend and restored in the response -->")
    w.variable("piiAnonymizationEnabled", "true")
    w.variable("piiConfidenceThreshold", f"{pii.confidence_threshold:g}")
    w.variable("piiEntityCategoryExclusions", ",".join(pii.excluded_categories))
    w.variable("piiDetectionLanguage", pii.language)
    if pii.max_chunk_size != _DEFAULT_PII.max_chunk_size:
        w.variable("piiMaxChunkSize", str(pii.max_chunk_size))
    if pii.chunk_overlap != _DEFAULT_PII.chunk_overlap:
        w.variable("piiChunkOverlap", str(pii.chunk_overlap))
    if pii.regex_patterns:
        w.expression_variable("piiRegexPatterns", _regex_patterns_expression(pii))
    w.expression_variable("piiInputContent", "@(context.Request.Body.As<string>(preserveContent: true))")
    w.line('<include-fragment fragment-id="pii-anonymization" />')
    if pii.mode == "anonymize":
        w.line('<set-body>@(context.Variables.GetValueOrDefault<string>("piiAnonymizedContent"))</set-body>')
        return
    w.open("<choose>")
    w.open(
        '<when condition="@{ var mappings = '
        'context.Variables.GetValueOrDefault<string>("piiMappings", "[]"); '
        'return JArray.Parse(mappings).Count > 0; }">'
    )
    w.open("<return-response>")
    w.line('<set-status code="400" reason="Bad Request" />')
    w.open('<set-header name="Content-Type" exists-action="override">')
    w.line("<value>application/json</value>")
    w.close("</set-header>")
    w.line("<set-body>" + _PII_BLOCK_RESPONSE_BODY + "</set-body>")
    w.close("</return-response>")
    w.close("</when>")
    w.close("</choose>")


def _emit_pii_outbound(w: _Writer, pii: PiiPolicy, *, llm_only_guard: bool) -> None:
    if pii.mode != "anonymize":
        return
    w.line("<!-- PII: restore original values in the response -->")
    if llm_only_guard:
        # Reading the response body breaks MCP streaming, so only LLM responses are processed.
        w.open("<choose>")
        w.open(
            '<when condition="@(context.Variables.GetValueOrDefault<string>("assetKind", "llm") == "llm")">'
        )
    w.expression_variable("responseBodyContent", "@(context.Response.Body.As<string>(preserveContent: true))")
    w.open("<choose>")
    w.open(
        '<when condition="@(context.Variables.GetValueOrDefault<string>("piiAnonymizationEnabled") == "true" '
        '&& context.Variables.ContainsKey("piiMappings"))">'
    )
    w.expression_variable(
        "piiDeanonymizeContentInput", '@(context.Variables.GetValueOrDefault<string>("responseBodyContent"))'
    )
    w.line('<include-fragment fragment-id="pii-deanonymization" />')
    if pii.save_state:
        w.variable("piiStateSavingEnabled", "true")
        w.expression_variable(
            "originalRequest", '@(context.Variables.GetValueOrDefault<string>("piiInputContent"))'
        )
        w.expression_variable(
            "originalResponse", '@(context.Variables.GetValueOrDefault<string>("responseBodyContent"))'
        )
        w.line('<include-fragment fragment-id="pii-state-saving" />')
    w.line(
        '<set-body>@(context.Variables.GetValueOrDefault<string>("piiDeanonymizedContentOutput"))</set-body>'
    )
    w.close("</when>")
    w.open("<otherwise>")
    w.line('<set-body>@(context.Variables.GetValueOrDefault<string>("responseBodyContent"))</set-body>')
    w.close("</otherwise>")
    w.close("</choose>")
    if llm_only_guard:
        w.close("</when>")
        w.close("</choose>")


def _emit_llm_controls(w: _Writer, policy: ProductPolicyIntent, *, validate_explicitly: bool) -> None:
    w.line('<include-fragment fragment-id="set-llm-requested-model" />')
    w.line("<!-- Model access: an empty list allows every model -->")
    w.variable("allowedModels", ",".join(policy.allowed_models))
    if policy.allowed_backend_pools:
        w.variable("allowedBackendPools", ",".join(policy.allowed_backend_pools))
    if validate_explicitly:
        w.line('<include-fragment fragment-id="validate-model-access" />')
    _emit_token_limits(w, policy)
    _emit_pii_inbound(w, policy.pii)


def _emit_call_limit(w: _Writer, limit: CallLimit, suffix: str) -> None:
    counter = f'@(context.Subscription.Id + ":{suffix}")'
    w.line(
        f'<rate-limit-by-key calls="{limit.calls}" renewal-period="{limit.renewal_period_seconds}" '
        f'counter-key="{counter}" remaining-calls-variable-name="{suffix}RateRemaining" />'
    )
    if limit.quota_calls is not None and limit.quota_period_seconds is not None:
        w.line(
            f'<quota-by-key calls="{limit.quota_calls}" renewal-period="{limit.quota_period_seconds}" '
            f'counter-key="{counter}" />'
        )


def _emit_multi_asset(w: _Writer, service: ServiceIntent) -> None:
    policy = service.policy
    w.line("<!-- Asset-type classification: unlisted APIs are treated as LLM APIs -->")
    w.variable("contractToolApis", ",".join(service.tool_apis))
    w.variable("contractAgentApis", ",".join(service.agent_apis))
    w.line('<include-fragment fragment-id="set-asset-kind" />')
    w.open("<choose>")
    w.open('<when condition="@(context.Variables.GetValueOrDefault<string>("assetKind","llm") == "llm")">')
    _emit_llm_controls(w, policy, validate_explicitly=True)
    w.close("</when>")
    if policy.tool_limits is not None:
        w.open('<when condition="@(context.Variables.GetValueOrDefault<string>("assetKind","") == "tool")">')
        _emit_call_limit(w, policy.tool_limits, "tool")
        w.close("</when>")
    if policy.agent_limits is not None:
        w.open('<when condition="@(context.Variables.GetValueOrDefault<string>("assetKind","") == "agent")">')
        _emit_call_limit(w, policy.agent_limits, "agent")
        w.close("</when>")
    w.close("</choose>")


def build_product_policy(service: ServiceIntent, ctx: PolicyBuildContext | None = None) -> str:
    """Render the product policy XML for one service of an access contract.

    Args:
        service: The service (product) intent, including its tool/agent API classification.
        ctx: Contract-level facts, such as whether the contract has a ProjectManagedIdentity
            Foundry connection.

    Returns:
        The policy document (APIM ``rawxml`` syntax) ending with a newline.

    Raises:
        PolicyBuildError: If the intent combines settings that cannot work together.
    """
    context = ctx or PolicyBuildContext()
    policy = service.policy
    _check_conflicts(policy, context)
    grants_llm = bool(service.llm_apis) or service.code == "LLM"

    w = _Writer()
    w.line(GENERATED_HEADER)
    w.open("<policies>")
    w.open("<inbound>")
    w.line("<base />")
    _emit_authentication(w, policy, context)
    _emit_alerts(w, policy.alerts)
    _emit_dimension(w, "customDimension1", policy.custom_dimension1)
    _emit_dimension(w, "customDimension2", policy.custom_dimension2)
    if policy.response_headers:
        w.line("<!-- Debug only: exposes UAIG-* routing headers -->")
        w.expression_variable("enableResponseHeaders", "@(true)")
    _emit_content_safety(w, policy.content_safety)
    if service.is_multi_asset:
        _emit_multi_asset(w, service)
    elif grants_llm:
        _emit_llm_controls(w, policy, validate_explicitly=False)
    w.close("</inbound>")
    w.open("<backend>")
    w.line("<base />")
    w.close("</backend>")
    w.open("<outbound>")
    w.line("<base />")
    if service.is_multi_asset or grants_llm:
        _emit_pii_outbound(w, policy.pii, llm_only_guard=service.is_multi_asset)
    w.close("</outbound>")
    w.open("<on-error>")
    w.line("<base />")
    w.close("</on-error>")
    w.close("</policies>")
    return w.text()
