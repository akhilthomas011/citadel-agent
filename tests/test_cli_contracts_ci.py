"""CI commands must fail loudly: a failed what-if or pre-deploy check may never look like success."""

from __future__ import annotations

from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest
from typer.testing import CliRunner

from citadel_agent import cli_contracts
from citadel_agent.azure_clients.deployments import DeploymentRecord, WhatIfChange, WhatIfReport
from citadel_agent.changes.changeset import StepKind
from citadel_agent.cli import app

runner = CliRunner()


class FakeRunner:
    def __init__(self, report: WhatIfReport) -> None:
        self.report = report
        self.deployed: list[str] = []

    def what_if(self, target: Any, name: str, compiled: Any) -> WhatIfReport:
        return self.report

    def deploy(self, target: Any, name: str, compiled: Any) -> DeploymentRecord:
        self.deployed.append(name)
        return DeploymentRecord(name=name, provisioning_state="Succeeded")


@pytest.fixture
def stubbed(monkeypatch: pytest.MonkeyPatch):
    def install(report: WhatIfReport) -> FakeRunner:
        step = SimpleNamespace(
            id="access-a",
            kind=StepKind.DEPLOY,
            parameters_file="contracts/a/main.bicepparam",
            subscription_id="11111111-1111-1111-1111-111111111111",
            location="swedencentral",
            deployment_name="dep-a",
            parameters_hash="p",
            template_hash="t",
        )
        change = SimpleNamespace(id="cs-1", environment="dev", executed_by=None, ordered_steps=lambda: [step])
        fake = FakeRunner(report)
        monkeypatch.setattr(cli_contracts, "_load_manifest", lambda repo, manifest: change)
        monkeypatch.setattr(cli_contracts, "_step_problems", lambda repo, step: [])
        monkeypatch.setattr(
            cli_contracts,
            "compile_deployment",
            lambda path: SimpleNamespace(parameters_hash="p", template_hash="t"),
        )
        monkeypatch.setattr(cli_contracts, "_runner", lambda subscription_id: fake)
        return fake

    return install


def test_whatif_with_changes_succeeds(stubbed, tmp_path: Path) -> None:
    ok = WhatIfReport(
        status="Succeeded",
        changes=(WhatIfChange("/subscriptions/s/resourceGroups/rg/providers/x/y/z", "Create"),),
    )
    stubbed(ok)

    result = runner.invoke(app, ["contracts", "whatif", "--repo", str(tmp_path), "--manifest", "m.json"])

    assert result.exit_code == 0, result.output
    assert "Create 1" in result.output


def test_whatif_error_is_not_reported_as_no_changes(stubbed, tmp_path: Path) -> None:
    stubbed(WhatIfReport(status="Failed", error="Authorization failed"))

    result = runner.invoke(app, ["contracts", "whatif", "--repo", str(tmp_path), "--manifest", "m.json"])

    assert result.exit_code == 1
    assert "what-if failed" in result.output
    assert "no changes" not in result.output
    assert "Authorization failed" in result.output


def test_deploy_stops_when_the_pre_deploy_whatif_fails(stubbed, tmp_path: Path) -> None:
    fake = stubbed(WhatIfReport(status="Failed", error="Authorization failed"))

    result = runner.invoke(app, ["contracts", "deploy", "--repo", str(tmp_path), "--manifest", "m.json"])

    assert result.exit_code == 1
    assert fake.deployed == []


def test_deploy_runs_after_a_clean_whatif(stubbed, tmp_path: Path) -> None:
    fake = stubbed(WhatIfReport(status="Succeeded"))

    result = runner.invoke(app, ["contracts", "deploy", "--repo", str(tmp_path), "--manifest", "m.json"])

    assert result.exit_code == 0, result.output
    assert fake.deployed == ["dep-a"]


# The real guard: a manifest is pull-request data and these commands run with credentials -------

GENERATED = "// Generated by citadel-agent from contract.yaml. Do not edit: change the contract intent.\n"
TEMPLATE = "upstream/ai-hub-gateway/bicep/infra/citadel-access-contracts/main.bicep"
SUBSCRIPTION = "11111111-1111-1111-1111-111111111111"


def _contract_repo(tmp_path: Path, *, header: str = GENERATED, using: str | None = None) -> Path:
    directory = tmp_path / "contracts" / "access" / "a" / "b" / "dev"
    directory.mkdir(parents=True)
    target = using or "../" * 5 + TEMPLATE
    (directory / "main.bicepparam").write_text(f"{header}\nusing '{target}'\n", encoding="utf-8")
    return tmp_path


def _step(**overrides: Any) -> SimpleNamespace:
    values = {
        "id": "access-a",
        "kind": StepKind.DEPLOY,
        "parameters_file": "contracts/access/a/b/dev/main.bicepparam",
        "template": TEMPLATE,
        "subscription_id": SUBSCRIPTION,
        "location": "swedencentral",
        "deployment_name": "dep-a",
        "parameters_hash": "p",
        "template_hash": "t",
    }
    return SimpleNamespace(**{**values, **overrides})


def test_a_generated_contract_step_passes_the_guard(tmp_path: Path) -> None:
    assert cli_contracts._step_problems(_contract_repo(tmp_path), _step()) == []


@pytest.mark.parametrize(
    ("overrides", "fragment"),
    [
        ({"parameters_file": ".citadel/changesets/x.bicepparam"}, "not a generated contracts"),
        ({"parameters_file": "contracts/access/../../x/main.bicepparam"}, "not a generated contracts"),
        ({"template": "contracts/evil/main.bicep"}, "not an upstream contract template"),
        ({"subscription_id": "x"}, "not a GUID"),
        ({"location": "a;b"}, "plain Azure region"),
    ],
)
def test_a_step_outside_the_contract_layout_is_refused(
    tmp_path: Path, overrides: dict[str, Any], fragment: str
) -> None:
    problems = cli_contracts._step_problems(_contract_repo(tmp_path), _step(**overrides))

    assert any(fragment in problem for problem in problems)


def test_a_hand_written_parameter_file_is_refused(tmp_path: Path) -> None:
    repo = _contract_repo(tmp_path, header="// written by hand\nparam x = readEnvironmentVariable('HOME')")

    assert any("not a file generated" in p for p in cli_contracts._step_problems(repo, _step()))


def test_a_parameter_file_using_another_template_is_refused(tmp_path: Path) -> None:
    repo = _contract_repo(tmp_path, using="../" * 5 + "upstream/ai-hub-gateway/bicep/infra/other/main.bicep")

    assert any("does not use the template" in p for p in cli_contracts._step_problems(repo, _step()))


@pytest.mark.parametrize("command", ["whatif", "deploy"])
def test_credentialed_commands_stop_before_compiling_or_deploying(
    command: str, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    repo = _contract_repo(tmp_path)
    step = _step(parameters_file=".citadel/changesets/x.bicepparam")
    change = SimpleNamespace(id="cs-1", environment="dev", executed_by=None, ordered_steps=lambda: [step])
    touched: list[str] = []
    monkeypatch.setattr(cli_contracts, "_load_manifest", lambda r, m: change)
    monkeypatch.setattr(cli_contracts, "compile_deployment", lambda path: touched.append("compile"))
    monkeypatch.setattr(cli_contracts, "_runner", lambda subscription_id: touched.append("runner"))

    result = runner.invoke(app, ["contracts", command, "--repo", str(repo), "--manifest", "m.json"])

    assert result.exit_code == 2
    assert "Refusing to run step 'access-a'" in result.output
    assert touched == []
